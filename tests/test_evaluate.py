from functools import partial
from pathlib import Path

import numpy as np

from quadrotor.evaluate import (
    attitude_error,
    correction_error,
    horizon_rollout_error,
    one_step_error,
    one_step_predictions,
    validation_score,
)
from quadrotor.integrators import rollout
from quadrotor.physics import f_pbm, load_params

P = load_params(Path(__file__).parents[1] / "configs" / "params.yaml")
DT = 0.0025
F = partial(f_pbm, p=P)
HOVER = np.sqrt(P.mass * P.g / (4 * P.kf))


def pbm_flight(n: int = 300, seed: int = 0) -> tuple[np.ndarray, np.ndarray]:
    """A 'measured' trajectory generated by the PBM itself (small motor wiggles around hover)."""
    rng = np.random.default_rng(seed)
    u = HOVER + rng.normal(0.0, 2.0, (n, 4))
    x0 = np.zeros(13)
    x0[6] = 1.0
    return rollout(x0, u, F, DT)[:n], u


def test_attitude_error_is_sign_invariant_and_correct() -> None:
    q = np.array([1.0, 0.0, 0.0, 0.0])
    q_rot = np.array([np.cos(0.25), np.sin(0.25), 0.0, 0.0])  # 0.5 rad about x
    assert np.isclose(attitude_error(q, q_rot), 0.5)
    assert np.isclose(attitude_error(q, -q), 0.0)


def test_perfect_model_has_zero_one_step_and_rollout_error() -> None:
    x, u = pbm_flight()
    assert all(v == 0.0 for v in one_step_error(one_step_predictions(x, u, F, DT), x[1:]).values())
    err = horizon_rollout_error(x, u, F, DT, [0.1, 0.25], stride=20)
    assert set(err) == {0.1, 0.25}
    assert all(e.shape[1] == 4 and np.all(e == 0.0) for e in err.values())
    assert validation_score(F, [(x, u, DT)], 0.25, 0.05) == 0.0


def test_wrong_model_has_growing_error_and_same_window_starts() -> None:
    x, u = pbm_flight()
    p_wrong = load_params(Path(__file__).parents[1] / "configs" / "params.yaml")
    f_wrong = partial(f_pbm, p=p_wrong, f_corr=np.array([0.2, 0.0, 0.0]))
    err = horizon_rollout_error(x, u, f_wrong, DT, [0.1, 0.25], stride=20)
    assert len(err[0.1]) == len(err[0.25])
    assert np.median(err[0.25][:, 0]) > np.median(err[0.1][:, 0]) > 0.0


def test_non_finite_rollout_scores_inf() -> None:
    x, u = pbm_flight(n=100)
    exploding = lambda xx, uu: np.full(13, np.nan)  # noqa: E731
    assert validation_score(exploding, [(x, u, DT)], 0.1, 0.025) == float("inf")


def test_correction_error_per_component() -> None:
    label = np.zeros((10, 6))
    pred = np.tile([1.0, 0, 0, 0, 0, 2.0], (10, 1))
    err = correction_error(pred, label)
    assert err["F_x"] == 1.0 and err["T_z"] == 2.0 and err["F_y"] == 0.0


def test_batched_windows_match_single_window_rollouts() -> None:
    x, u = pbm_flight(n=200, seed=3)
    f_wrong = partial(f_pbm, p=P, f_corr=np.array([0.1, -0.05, 0.2]))
    err = horizon_rollout_error(x, u, f_wrong, DT, [0.1], stride=7)[0.1]
    n = int(round(0.1 / DT))
    from quadrotor.dataset import window_starts
    from quadrotor.evaluate import state_errors
    for j, i in enumerate(window_starts(len(x), n, 7)):
        single = state_errors(rollout(x[i], u[i : i + n], f_wrong, DT)[-1], x[i + n])
        assert np.allclose(err[j], single, rtol=1e-10, atol=1e-13)
